package com.example.flowave.data.ytmusic

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test
import java.security.MessageDigest

/**
 * Unit tests for YouTube Music authentication, cookie normalization,
 * JSON map serialization, connection state, and SAPISIDHASH derivation.
 */
class YtMusicAuthTest {

    @Test
    fun testNormalizeStandardCookieHeader() {
        val input = "SID=abc123xyz; SAPISID=sapi_secret_token; HSID=h123"
        val normalized = CookieNormalizer.normalize(input)

        assertTrue(normalized.contains("SAPISID=sapi_secret_token"))
        assertTrue(normalized.contains("SID=abc123xyz"))
        assertTrue(normalized.contains("HSID=h123"))
        // Check sorted alphabetical order
        assertEquals("HSID=h123; SAPISID=sapi_secret_token; SID=abc123xyz", normalized)
    }

    @Test
    fun testNormalizeNetscapeCookiesTxt() {
        val input = """
            # Netscape HTTP Cookie File
            # http://curl.haxx.se/rfc/cookie_spec.html
            # This file was generated by libcurl! Edit at your own risk.
            .youtube.com	TRUE	/	TRUE	1893456000	__Secure-3PAPISID	secure_sapisid_value
            #HttpOnly_.youtube.com	TRUE	/	TRUE	1893456000	SSID	ssid_value
        """.trimIndent()

        val normalized = CookieNormalizer.normalize(input)
        assertTrue(normalized.contains("__Secure-3PAPISID=secure_sapisid_value"))
        assertTrue(normalized.contains("SSID=ssid_value"))
    }

    @Test
    fun testNormalizeJsonExtensionExport() {
        val input = """
            [
              {"domain": ".youtube.com", "name": "SAPISID", "value": "val_sapisid"},
              {"domain": ".youtube.com", "name": "SID", "value": "val_sid"}
            ]
        """.trimIndent()

        val normalized = CookieNormalizer.normalize(input)
        assertEquals("SAPISID=val_sapisid; SID=val_sid", normalized)
    }

    @Test
    fun testNormalizeMissingSapisidThrows() {
        val input = "SID=only_sid; HSID=only_hsid"
        try {
            CookieNormalizer.normalize(input)
            fail("Should throw IllegalArgumentException when missing SAPISID")
        } catch (e: IllegalArgumentException) {
            assertTrue(e.message?.contains("Missing SAPISID") == true)
        }
    }

    @Test
    fun testNormalizeEmptyThrows() {
        try {
            CookieNormalizer.normalize("   ")
            fail("Should throw IllegalArgumentException when empty")
        } catch (e: IllegalArgumentException) {
            assertTrue(e.message?.contains("Please enter cookie text") == true)
        }
    }

    @Test
    fun testCookieMapEncodeDecodeRoundTrip() {
        val original = mapOf(
            "SAPISID" to "token_123",
            "SID" to "sid_val",
            "QUOTED" to "value with \"quotes\" and \n newline"
        )
        val encoded = YtMusicPreferences.encodeCookieMap(original)
        val decoded = YtMusicPreferences.decodeCookieMap(encoded)

        assertEquals("token_123", decoded["SAPISID"])
        assertEquals("sid_val", decoded["SID"])
        assertEquals(original["QUOTED"], decoded["QUOTED"])
    }

    @Test
    fun testYtConnectionIsConnected() {
        assertFalse(YtConnection.DISCONNECTED.isConnected)

        val connected = YtConnection(
            cookies = mapOf("SAPISID" to "token"),
            accountName = "Tester",
            channelHandle = "@tester",
            photoUrl = "https://example.com/avatar.jpg"
        )
        assertTrue(connected.isConnected)

        val emptyCookies = YtConnection(
            cookies = emptyMap(),
            accountName = "Tester"
        )
        assertFalse(emptyCookies.isConnected)

        val blankName = YtConnection(
            cookies = mapOf("SAPISID" to "token"),
            accountName = "   "
        )
        assertFalse(blankName.isConnected)
    }

    @Test
    fun testSapisidHashComputation() {
        val timestamp = 1700000000L
        val token = "my_sample_sapisid_token"
        val origin = "https://music.youtube.com"

        val payload = "$timestamp $token $origin"
        val digest = MessageDigest.getInstance("SHA-1").digest(payload.toByteArray(Charsets.UTF_8))
        val hex = digest.joinToString("") { "%02x".format(it) }
        val header = "SAPISIDHASH ${timestamp}_$hex"

        assertNotNull(header)
        assertTrue(header.startsWith("SAPISIDHASH 1700000000_"))
        assertEquals(40, hex.length) // SHA-1 is 40 hex chars
    }
}
